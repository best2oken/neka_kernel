; void context_switch64(uint64_t *old_rsp_ptr, uint64_t new_rsp)
; System V AMD64 ABI: 1-й аргумент в RDI, 2-й в RSI.
; Callee-saved регистры (обязаны быть сохранены через вызов функции) —
; RBP, RBX, R12, R13, R14, R15. Ровно их и сохраняем/восстанавливаем —
; ABI гарантирует, что вызывающий код не полагается на остальные (RAX,
; RCX, RDX, RSI, RDI, R8-R11) через границу вызова функции.
bits 64
section .text
global context_switch64

; БАГ, найденный на практике: RFLAGS (включая IF — флаг разрешения
; прерываний) раньше НЕ входил в сохраняемое здесь состояние. Это было
; безопасно, ПОКА все переключения происходили ИСКЛЮЧИТЕЛЬНО из
; обработчика прерывания (там RFLAGS естественно едет в кадре
; прерывания и восстанавливается через iretq). Но NKern_Unlock() может
; вызвать sched64_reschedule() ПРЯМО ИЗ ОБЫЧНОГО КОДА потока (не из
; прерывания) — в этом случае IF потока, В КОТОРЫЙ мы переключаемся,
; никогда не восстанавливался бы правильно (он просто наследовал бы
; ТЕКУЩЕЕ, чужое состояние IF в момент свитча) — это давало испорченный
; RSP/выполнение (гонка: поток мог быть прерван ПОСЕРЕДИНЕ самого
; context_switch64, пока RDI/RSI ещё не отработали до конца). Теперь
; RFLAGS — часть сохранённого контекста, как и callee-saved регистры.
context_switch64:
    pushfq
    push rbp
    push rbx
    push r12
    push r13
    push r14
    push r15

    mov [rdi], rsp     ; *old_rsp_ptr = rsp (сохранить стек старого потока)
    mov rsp, rsi        ; rsp = new_rsp     (переключиться на стек нового потока)

    pop r15
    pop r14
    pop r13
    pop r12
    pop rbx
    pop rbp
    popfq
    ret

; thread_start64 — точка первого входа для НОВОГО потока.
;
; Раньше здесь был голый "sti" (чинил баг с потерянным IF для потоков,
; впервые стартующих изнутри прерывания). Теперь вместо этого зовём
; NKern_UnlockAfterSwitch() — она тоже безусловно делает sti, но
; ВДОБАВОК корректно отпускает scheduler-лок, который держит тот, кто
; НАС сюда переключил (см. sched64.c: NKern_LockForSwitch() в
; sched64_reschedule() берёт лок ДО context_switch64() и НЕ отпускает
; его сама — ждёт, чтобы это сделала СТОРОНА, реально принявшая
; переключение, будь то возобновившийся поток или, как здесь, только
; что созданный).
;
; sched64_create_thread кладёт на стек: [entry][thread_start64][regs x6]
; ret из context_switch64 приземляется сюда; entry ещё лежит на стеке.
extern NKern_UnlockAfterSwitch
global thread_start64
thread_start64:
    call NKern_UnlockAfterSwitch
    pop rax        ; забираем entry (следующее значение на стеке)
    jmp rax        ; прыгаем в саму функцию потока
